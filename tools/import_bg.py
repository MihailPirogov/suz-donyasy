#!/usr/bin/env python3
"""Import chapter photo backgrounds.
Usage: tools/import_bg.py [src_dir=src/bg_stage]  (chNN.jpg 1280x720 originals; optional chNN_p.png / chNN_w.png from tools/upscale_bg.py)
Writes img/bg/chNN.webp (1080x1920 portrait) and chNN_l.webp (1920x1080 wide), ~150-250 KB each,
rewrites js/bgimages.js and screens/photo_bg_sheet.jpg."""
import sys, os, io
from PIL import Image, ImageDraw, ImageFilter
FX = {8: .38, 15: .6, 37: .75, 48: .42}  # horizontal crop position for off-centre subjects; keep in sync with tools/upscale_bg.py
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'img', 'bg')

def crop_lz(im, W, H, fx=.5):
    w = round(im.height * W / H)
    if w <= im.width: x = int((im.width - w) * fx); im = im.crop((x, 0, x + w, im.height))
    return im.resize((W, H), Image.LANCZOS)

def save(im, path, lo=150_000, hi=250_000):
    q = 82
    for _ in range(10):
        b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6); n = b.tell()
        if n > hi and q > 40: q -= 6
        elif n < lo and q < 92: q += 3
        else: break
    open(path, 'wb').write(b.getvalue()); return n

def main(src):
    os.makedirs(OUT, exist_ok=True); have = []; total = 0
    for n in range(1, 51):
        base = os.path.join(src, 'ch%02d' % n)
        if not os.path.exists(base + '.jpg'): continue
        im = Image.open(base + '.jpg').convert('RGB')
        for suf, W, H, out, lo in (('_p', 1080, 1920, 'ch%02d.webp', 150_000), ('_w', 1920, 1080, 'ch%02d_l.webp', 120_000)):
            lz = crop_lz(im, W, H, FX.get(n, .5) if suf == '_p' else .5)
            if os.path.exists(base + suf + '.png'):  # Real-ESRGAN result blended 80/20 with Lanczos for a natural look
                img = Image.blend(lz, Image.open(base + suf + '.png').convert('RGB').resize((W, H), Image.LANCZOS), .8)
            else: img = lz.filter(ImageFilter.UnsharpMask(1.2, 40, 2))
            total += save(img, os.path.join(OUT, out % n), lo)
        have.append(n)
    open(os.path.join(ROOT, 'js', 'bgimages.js'), 'w').write(
        '/* Chapter photo backgrounds in img/bg/chNN.webp (+ chNN_l.webp wide); missing ones fall back to js/art.js SVG. Generated by tools/import_bg.py */\n'
        'window.BG_IMAGES = %s;\n' % have)
    tw, th, cols = 216, 384, 10; rows = (len(have) + cols - 1) // cols or 1
    sheet = Image.new('RGB', (cols * tw, rows * (th + 22)), '#10302b'); d = ImageDraw.Draw(sheet)
    for i, n in enumerate(have):
        t = Image.open(os.path.join(OUT, 'ch%02d.webp' % n)).resize((tw, th), Image.LANCZOS)
        x, y = i % cols * tw, i // cols * (th + 22); sheet.paste(t, (x, y)); d.text((x + 6, y + th + 5), 'ch%02d' % n, fill='#e9b949')
    os.makedirs(os.path.join(ROOT, 'screens'), exist_ok=True)
    sheet.save(os.path.join(ROOT, 'screens', 'photo_bg_sheet.jpg'), quality=86)
    print('imported', len(have), 'chapters, %.1f MB' % (total / 1e6))

if __name__ == '__main__': main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'src', 'bg_stage'))
